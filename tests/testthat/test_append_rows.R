context("native row append")

test_that("native row append validates arguments and integrates with column append", {
  path <- tempfile(); on.exit(unlink(path))
  x <- data.frame(a = 1:4)
  expect_null(fstcore:::fststore(path, x, 50L, TRUE))
  for (bad in list(integer(), NA_integer_, c(1L, 2L), 101L, 50))
    expect_s3_class(fstcore:::fstappendrows(path, x, bad, TRUE), "fst_error")
  for (bad in list(logical(), NA, c(TRUE, FALSE), 1L))
    expect_s3_class(fstcore:::fstappendrows(path, x, 50L, bad), "fst_error")
  for (bad in list(NULL, 1:4, list(), list(b = 1:4), list(a = double(4))))
    expect_s3_class(fstcore:::fstappendrows(path, bad, 50L, TRUE), "fst_error")
  expect_null(fstcore:::fstappendrows(path, list(a = 5:8), 50L, TRUE))
  expect_identical(fstcore:::fstretrieve(path, NULL, 1, NULL)$resTable$a, 1:8)
  expect_null(fstcore:::fstappend(path, data.frame(b = 11:18), 50L, TRUE))
  expect_null(fstcore:::fstappendrows(path, list(a = 9:10, b = 19:20), 100L, TRUE))
  result <- fstcore:::fstretrieve(path, c("b", "a"), 7, 10)
  expect_identical(result$resTable, list(b = 17:20, a = 7:10))
})
